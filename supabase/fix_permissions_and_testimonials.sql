-- 1. Grant schema usage and table privileges to Supabase built-in roles
GRANT USAGE ON SCHEMA public TO anon, authenticated, service_role;
GRANT ALL ON ALL TABLES IN SCHEMA public TO anon, authenticated, service_role;
GRANT ALL ON ALL SEQUENCES IN SCHEMA public TO anon, authenticated, service_role;
GRANT ALL ON ALL ROUTINES IN SCHEMA public TO anon, authenticated, service_role;

ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON TABLES TO anon, authenticated, service_role;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON SEQUENCES TO anon, authenticated, service_role;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON ROUTINES TO anon, authenticated, service_role;

-- 2. Ensure testimonials table exists
CREATE TABLE IF NOT EXISTS "testimonials" (
    "id"         BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "testi_id"   VARCHAR(50)  NOT NULL,
    "quote"      TEXT         NOT NULL,
    "name"       VARCHAR(255) NOT NULL,
    "role"       VARCHAR(255)          DEFAULT NULL,
    "avatar"     VARCHAR(500)          DEFAULT NULL,
    "rating"     SMALLINT      NOT NULL DEFAULT 5 CHECK ("rating" BETWEEN -128 AND 127),
    "tag"        VARCHAR(100)          DEFAULT NULL,
    "sort_order" INT          NOT NULL DEFAULT 0,
    "status"     VARCHAR(8) NOT NULL DEFAULT 'active' CHECK ("status" IN ('active', 'inactive')),
    "created_at" TIMESTAMP WITHOUT TIME ZONE     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "updated_at" TIMESTAMP WITHOUT TIME ZONE     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY ("id"),
    CONSTRAINT "uq_testi_id" UNIQUE ("testi_id")
);

-- 3. Row Level Security policies
ALTER TABLE "testimonials" ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Public can view active testimonials" ON "testimonials";
CREATE POLICY "Public can view active testimonials"
    ON "testimonials" FOR SELECT
    USING (status = 'active');

DROP POLICY IF EXISTS "Service role has full access to testimonials" ON "testimonials";
CREATE POLICY "Service role has full access to testimonials"
    ON "testimonials" FOR ALL
    TO service_role
    USING (true)
    WITH CHECK (true);

